#!/usr/bin/env node
// Writes .github/MESSAGE_PREVIEW.md: a sample of station control's issues and
// comments, so a maintainer can open that file on GitHub and see how they
// render (character colours, cards, checklists, folds) without playing.
//
//   node scripts/preview-messages.mjs

import { writeFileSync } from 'node:fs';
import * as m from './lib/messages.mjs';
import { SCREENSHOT_LIST, STEPS, confirmation, directPushUndone, stepIssue } from './lib/missions.mjs';

const ctx = { link: 2, handoverPr: 7, discrepancy: 10, reviewPr: 12 };
// Images load from this repository's own folder in the preview.
const SHOTS = 'https://raw.githubusercontent.com/TashaGandevia/stage-05-claude/main/.github/screenshots';
const task = (key, number) => stepIssue(key, ctx).body.replaceAll(m.ISSUE_NUMBER, String(number)).replaceAll(m.SCREENSHOTS, SHOTS);

const findings = [
  { ok: true, kind: 'content', text: 'Ship is Aster, at Bay 3' },
  { ok: false, kind: 'content', text: 'Expected time `22.40` should be 24-hour `HH:MM`' },
  { ok: false, kind: 'link', text: 'The description should say `Closes #6`' },
  { ok: false, kind: 'advice', text: "A commit looks like it was made on GitHub's website" },
];

const sample = [
  ['M14.1 · Take the request (issue)', task('14.1', 1)],
  ['Mika confirms M14.1 (comment)', confirmation('14.1', { c: { assigned: true }, next: { number: 2, title: 'M14.2 · Open a pull request' }, login: 'learner', self: 1 })],
  ['M14.2 · Open a pull request (issue)', task('14.2', 2)],
  ['M14.3 · Check and merge (issue)', task('14.3', 4)],
  ['Next step pointer (comment on a pull request)', m.nextStep(4, 'M14.3 · Check and merge')],
  ['Record checks comment: errors and warnings', m.inspectionReport({ evaluation: { parts: [{ title: 'Validate handover', findings }], readiness: null, scope: 'Record checks validate the record format.' }, sha: 'abc1234def', runUrl: 'https://github.com', passedAll: false })],
  ['A failed check (Voss, on a pull request)', m.vossFailedCheck],
  ['Voss undoes a direct push to main', directPushUndone({ step: 1, closes: 3, files: ['docking-log/plans/aster.md'], login: 'learner' })],
  ['Stage complete', m.stageComplete],
];

const page = [
  '# Message preview',
  '',
  'Generated by `scripts/preview-messages.mjs`. Not part of the story: it shows how station control\'s issues and comments render on GitHub.',
  '',
  ...sample.flatMap(([title, body]) => ['---', '', `## ${title}`, '', body, '']),
].join('\n');

writeFileSync(new URL('../.github/MESSAGE_PREVIEW.md', import.meta.url), page);
console.log('Wrote .github/MESSAGE_PREVIEW.md');

// Every screenshot the tasks expect, so the maintainer knows what to save as what.
for (const key of Object.keys(STEPS)) STEPS[key]({ ...ctx, self: 1, link: 2 });
const rows = [...SCREENSHOT_LIST].sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true }))
  .map(([name, description]) => `| \`${name}.png\` | ${description} |`);
writeFileSync(new URL('../.github/screenshots/README.md', import.meta.url), [
  '# Screenshots',
  '',
  'Images for the task issues. Save each one here with exactly this name; issues load them from this folder in the learner\'s own copy of the repository. Until a file exists, its issue shows a broken image.',
  '',
  'Generated by `scripts/preview-messages.mjs` from the `shot(...)` calls in `scripts/lib/missions.mjs`.',
  '',
  '| File | What it should show |',
  '|---|---|',
  ...rows,
  '',
].join('\n'));
console.log(`Wrote .github/screenshots/README.md (${rows.length} screenshots)`);
